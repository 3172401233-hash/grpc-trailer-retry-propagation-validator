export const GRPC_STATUS = {
  OK: 0,
  CANCELLED: 1,
  UNKNOWN: 2,
  INVALID_ARGUMENT: 3,
  DEADLINE_EXCEEDED: 4,
  NOT_FOUND: 5,
  ALREADY_EXISTS: 6,
  PERMISSION_DENIED: 7,
  RESOURCE_EXHAUSTED: 8,
  FAILED_PRECONDITION: 9,
  ABORTED: 10,
  OUT_OF_RANGE: 11,
  UNIMPLEMENTED: 12,
  INTERNAL: 13,
  UNAVAILABLE: 14,
  DATA_LOSS: 15,
  UNAUTHENTICATED: 16
};

export const GRPC_STATUS_NAME = Object.fromEntries(
  Object.entries(GRPC_STATUS).map(([name, code]) => [code, name])
);

export function grpcStatusName(code) {
  return GRPC_STATUS_NAME[code] ?? `UNKNOWN_CODE(${code})`;
}

// gRPC over HTTP/2 规范规定的 gRPC status -> HTTP status 映射。
// https://github.com/grpc/grpc/blob/master/doc/http-grpc-status-mapping.md
export const GRPC_TO_HTTP = {
  [GRPC_STATUS.OK]: 200,
  [GRPC_STATUS.INVALID_ARGUMENT]: 400,
  [GRPC_STATUS.OUT_OF_RANGE]: 400,
  [GRPC_STATUS.UNAUTHENTICATED]: 401,
  [GRPC_STATUS.PERMISSION_DENIED]: 403,
  [GRPC_STATUS.NOT_FOUND]: 404,
  [GRPC_STATUS.ABORTED]: 409,
  [GRPC_STATUS.ALREADY_EXISTS]: 409,
  [GRPC_STATUS.RESOURCE_EXHAUSTED]: 429,
  [GRPC_STATUS.CANCELLED]: 499,
  [GRPC_STATUS.INTERNAL]: 500,
  [GRPC_STATUS.DATA_LOSS]: 500,
  [GRPC_STATUS.UNKNOWN]: 500,
  [GRPC_STATUS.UNIMPLEMENTED]: 501,
  [GRPC_STATUS.FAILED_PRECONDITION]: 400,
  [GRPC_STATUS.UNAVAILABLE]: 503,
  [GRPC_STATUS.DEADLINE_EXCEEDED]: 504
};

// 代理只看到 HTTP 状态时的反向映射（与 grpc-go 的 HTTPStatusToGRPCCode 对齐）。
export const HTTP_TO_GRPC = {
  200: GRPC_STATUS.OK,
  400: GRPC_STATUS.INTERNAL,
  401: GRPC_STATUS.UNAUTHENTICATED,
  403: GRPC_STATUS.PERMISSION_DENIED,
  404: GRPC_STATUS.UNIMPLEMENTED,
  409: GRPC_STATUS.ABORTED,
  429: GRPC_STATUS.RESOURCE_EXHAUSTED,
  499: GRPC_STATUS.CANCELLED,
  500: GRPC_STATUS.INTERNAL,
  501: GRPC_STATUS.UNIMPLEMENTED,
  502: GRPC_STATUS.UNAVAILABLE,
  503: GRPC_STATUS.UNAVAILABLE,
  504: GRPC_STATUS.DEADLINE_EXCEEDED
};

export function grpcToHttp(code) {
  return GRPC_TO_HTTP[code] ?? 500;
}

export function httpToGrpc(httpStatus) {
  return HTTP_TO_GRPC[httpStatus] ?? GRPC_STATUS.UNKNOWN;
}
